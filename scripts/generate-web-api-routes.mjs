#!/usr/bin/env node
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { WEB_API_ROUTE_DEFINITIONS } from "../src/web/web-api-contract.ts";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const targetPath = path.join(root, "src", "web", "ui", "client", "core", "api-routes.generated.js");
const typesTargetPath = path.join(root, "src", "web", "ui", "client", "core", "api-client-types.d.ts");
const checkOnly = process.argv.includes("--check");

const routeRules = WEB_API_ROUTE_DEFINITIONS.map((route) => ({
  ...(route.pattern ? { re: route.pattern } : { path: route.path }),
  methods: [...route.methods],
}));

const body = `// @ts-check
// Generated by scripts/generate-web-api-routes.mjs from src/web/web-api-contract.ts.
// Do not edit by hand.

/** @typedef {{ path: string; methods: import("../../../web-api-types.js").WebApiMethod[] } | { re: RegExp; methods: import("../../../web-api-types.js").WebApiMethod[] }} ApiRouteRule */

/** @type {ApiRouteRule[]} */
const WEB_API_CLIENT_ROUTE_RULES = [
${routeRules.map((route) => {
  const methods = `[${route.methods.map((method) => `'${method}'`).join(", ")}]`;
  if ("re" in route) {
    return `  { re: ${regexLiteral(route.re)}, methods: ${methods} },`;
  }
  return `  { path: ${JSON.stringify(route.path)}, methods: ${methods} },`;
}).join("\n")}
];

/** @type {{ NORDRELAY_WEB_API_CLIENT_ROUTE_RULES?: ApiRouteRule[] }} */ (globalThis).NORDRELAY_WEB_API_CLIENT_ROUTE_RULES = WEB_API_CLIENT_ROUTE_RULES;
`;

const staticPaths = WEB_API_ROUTE_DEFINITIONS
  .filter((route) => !route.dynamicType)
  .map((route) => route.path)
  .sort();
const dynamicPaths = WEB_API_ROUTE_DEFINITIONS
  .map((route) => route.dynamicType)
  .filter(Boolean)
  .sort();
const typesBody = `// Generated by scripts/generate-web-api-routes.mjs from src/web/web-api-contract.ts.
// Do not edit by hand.

export type WebApiMethod = "GET" | "POST" | "PATCH" | "PUT" | "DELETE";
export type WebApiQueryValue = string | number | boolean | null | undefined;
export type WebApiQuery = Record<string, WebApiQueryValue | WebApiQueryValue[]>;

export type WebApiStaticPath =
${staticPaths.map((item) => `  | ${JSON.stringify(item)}`).join("\n")};

export type WebApiDynamicPath =
${dynamicPaths.map((item) => `  | \`${item}\``).join("\n")};

export type WebApiKnownPath = WebApiStaticPath | WebApiDynamicPath;
export type WebApiPath = WebApiKnownPath | (string & {});

export interface WebApiClientOptions<P extends WebApiPath = WebApiPath> {
  method?: WebApiMethod;
  query?: WebApiQuery;
  headers?: Record<string, string>;
  body?: WebApiRequestBody<P> | string | FormData | Blob | ArrayBuffer | null;
}

export type WebApiRequestBody<P extends WebApiPath> =
  P extends "/api/prompt" ? { text: string; correlationId?: string } :
  P extends "/api/prompt/upload" ? { text?: string; correlationId?: string; files: Array<{ name: string; mimeType?: string; dataBase64: string }> } :
  P extends "/api/agent" ? { agentId: string } :
  P extends "/api/agent-update" ? { agentId: string; operation?: "update" | "install" } :
  P extends "/api/sessions/new" ? { agentId?: string; workspace?: string; workspaceMode?: "shared" | "worktree" | "attached"; model?: string; reasoningEffort?: string; launchProfileId?: string; fastMode?: boolean } :
  P extends "/api/sessions/worktrees/fork" ? { includeUncommitted?: boolean } :
  P extends "/api/sessions/worktrees/integrate" ? { ids: string[]; resolutions?: Array<{ path: string; choice: "auto" | "ours" | "theirs" | "both" | "manual"; sourceWorktreeId?: string; content?: string }> } :
  P extends "/api/sessions/worktrees/integrate/preview" ? { ids: string[] } :
  P extends "/api/sessions/worktrees/cleanup" ? Record<string, never> :
  P extends \`/api/sessions/worktrees/\${string}/commit\` ? { message?: string } :
  P extends \`/api/sessions/worktrees/\${string}/update\` ? Record<string, never> :
  P extends \`/api/sessions/worktrees/\${string}\` ? { force?: boolean } :
  P extends "/api/sessions/switch" | "/api/sessions/attach" ? { threadId: string } :
  P extends "/api/session/model" ? { model: string } :
  P extends "/api/session/reasoning" ? { reasoning: string } :
  P extends "/api/session/fast" ? { enabled: boolean } :
  P extends "/api/session/launch" ? { profileId: string; apply?: boolean } :
  P extends "/api/queue" ? { action: string; id?: string } :
  P extends "/api/peers/relay" ? { action: "cancel"; peerId: string; id: string } | { action: "retry"; peerId?: string; id?: string } | { action: "drain-expired" } :
  P extends "/api/settings" ? { settings: Record<string, string | null | undefined> } :
  P extends "/api/templates" | \`/api/templates/\${string}\` ? Record<string, unknown> :
  P extends \`/api/templates/\${string}/run\` | \`/api/templates/\${string}/preview\` ? { variables?: Record<string, string> } :
  P extends "/api/workflows" | \`/api/workflows/\${string}\` ? Record<string, unknown> :
  P extends \`/api/workflows/\${string}/run\` | \`/api/workflows/\${string}/preview\` ? { variables?: Record<string, string> } :
  P extends \`/api/workflow-runs/\${string}/cancel\` | \`/api/workflow-runs/\${string}/rerun-failed\` ? Record<string, never> :
  Record<string, unknown>;

export type WebApiClientResponse<P extends WebApiPath> = any;
`;

if (checkOnly) {
  const current = readFileSync(targetPath, "utf8");
  if (normalizeNewlines(current) !== normalizeNewlines(body)) {
    throw new Error("Generated WebUI API route rules are out of date. Run npm run api:generate.");
  }
  const currentTypes = readFileSync(typesTargetPath, "utf8");
  if (normalizeNewlines(currentTypes) !== normalizeNewlines(typesBody)) {
    throw new Error("Generated WebUI API client types are out of date. Run npm run api:generate.");
  }
} else {
  writeFileSync(targetPath, body, "utf8");
  writeFileSync(typesTargetPath, typesBody, "utf8");
}

function regexLiteral(source) {
  return `/${source.replace(/\//g, "\\/")}/`;
}

function normalizeNewlines(value) {
  return value.replace(/\r\n/g, "\n");
}
