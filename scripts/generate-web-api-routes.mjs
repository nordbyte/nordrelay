#!/usr/bin/env node
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { WEB_API_ROUTE_DEFINITIONS } from "../src/web/web-api-contract.ts";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const targetPath = path.join(root, "src", "web", "ui", "client", "core", "api-routes.generated.js");
const typesTargetPath = path.join(root, "src", "web", "ui", "client", "core", "api-client-types.d.ts");
const checkOnly = process.argv.includes("--check");

const routeRules = WEB_API_ROUTE_DEFINITIONS.map((route) => ({
  ...(route.pattern ? { re: route.pattern } : { path: route.path }),
  methods: [...route.methods],
}));

const body = `// @ts-check
// Generated by scripts/generate-web-api-routes.mjs from src/web/web-api-contract.ts.
// Do not edit by hand.

/** @typedef {{ path: string; methods: import("../../../web-api-types.js").WebApiMethod[] } | { re: RegExp; methods: import("../../../web-api-types.js").WebApiMethod[] }} ApiRouteRule */

/** @type {ApiRouteRule[]} */
const WEB_API_CLIENT_ROUTE_RULES = [
${routeRules.map((route) => {
  const methods = `[${route.methods.map((method) => `'${method}'`).join(", ")}]`;
  if ("re" in route) {
    return `  { re: ${regexLiteral(route.re)}, methods: ${methods} },`;
  }
  return `  { path: ${JSON.stringify(route.path)}, methods: ${methods} },`;
}).join("\n")}
];

/** @type {{ NORDRELAY_WEB_API_CLIENT_ROUTE_RULES?: ApiRouteRule[] }} */ (globalThis).NORDRELAY_WEB_API_CLIENT_ROUTE_RULES = WEB_API_CLIENT_ROUTE_RULES;
`;

const staticPaths = WEB_API_ROUTE_DEFINITIONS
  .filter((route) => !route.dynamicType)
  .map((route) => route.path)
  .sort();
const dynamicPaths = WEB_API_ROUTE_DEFINITIONS
  .map((route) => route.dynamicType)
  .filter(Boolean)
  .sort();
const typesBody = `// Generated by scripts/generate-web-api-routes.mjs from src/web/web-api-contract.ts.
// Do not edit by hand.

import type {
  WebApiClientResponse as ServerWebApiClientResponse,
  WebApiMethod as ServerWebApiMethod,
  WebApiPath as ServerWebApiPath,
  WebApiQuery as ServerWebApiQuery,
  WebApiQueryValue as ServerWebApiQueryValue,
  WebApiRequestBody as ServerWebApiRequestBody,
} from "../../../web-api-types.js";

export type WebApiMethod = ServerWebApiMethod;
export type WebApiQueryValue = ServerWebApiQueryValue;
export type WebApiQuery = ServerWebApiQuery;

export type WebApiStaticPath =
${staticPaths.map((item) => `  | ${JSON.stringify(item)}`).join("\n")};

export type WebApiDynamicPath =
${dynamicPaths.map((item) => `  | \`${item}\``).join("\n")};

export type WebApiKnownPath = WebApiStaticPath | WebApiDynamicPath;
export type WebApiPath = WebApiKnownPath | (string & {});

export type WebApiResponseByPath = {
${staticPaths.map((item) => `  ${JSON.stringify(item)}: ServerWebApiClientResponse<${JSON.stringify(item)}>;`).join("\n")}
};

export type WebApiRequestBodyByPath = {
${staticPaths.map((item) => `  ${JSON.stringify(item)}: ServerWebApiRequestBody<${JSON.stringify(item)}>;`).join("\n")}
};

export interface WebApiClientOptions<P extends WebApiPath = WebApiPath> {
  method?: WebApiMethod;
  query?: WebApiQuery;
  headers?: Record<string, string>;
  body?: WebApiRequestBody<P> | string | FormData | Blob | ArrayBuffer | null;
  timeoutMs?: number;
  contextKey?: string;
}

export type WebApiRequestBody<P extends WebApiPath> =
  P extends keyof WebApiRequestBodyByPath ? WebApiRequestBodyByPath[P] :
  P extends ServerWebApiPath ? ServerWebApiRequestBody<P> : Record<string, unknown>;

export type WebApiClientResponse<P extends WebApiPath> =
  P extends keyof WebApiResponseByPath ? WebApiResponseByPath[P] :
  P extends ServerWebApiPath ? ServerWebApiClientResponse<P> : unknown;
`;

if (checkOnly) {
  const current = readFileSync(targetPath, "utf8");
  if (normalizeNewlines(current) !== normalizeNewlines(body)) {
    throw new Error("Generated WebUI API route rules are out of date. Run npm run api:generate.");
  }
  const currentTypes = readFileSync(typesTargetPath, "utf8");
  if (normalizeNewlines(currentTypes) !== normalizeNewlines(typesBody)) {
    throw new Error("Generated WebUI API client types are out of date. Run npm run api:generate.");
  }
} else {
  writeFileSync(targetPath, body, "utf8");
  writeFileSync(typesTargetPath, typesBody, "utf8");
}

function regexLiteral(source) {
  return `/${source.replace(/\//g, "\\/")}/`;
}

function normalizeNewlines(value) {
  return value.replace(/\r\n/g, "\n");
}
